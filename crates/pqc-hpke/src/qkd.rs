//! Experimental, in-memory delivery of paired simulated QKD keys.
//!
//! This is a protocol-integration fixture, not a QKD implementation or
//! secure network key management entity. Each party has its own store.
//! Authenticated peer identities and genuine QKD security are outside this
//! module's scope. Keys are removed on acquisition, even if later HPKE fails.

use std::collections::{BTreeMap, BTreeSet};
use zeroize::Zeroizing;

/// Provenance of key material delivered by the experimental provider.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QkdProvenance {
    /// Artificial test material, not generated by a QKD security protocol.
    SimulationFixture,
}

/// Errors returned by the experimental QKD provider.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QkdProviderError {
    /// The identifier or party names were empty, or participants were equal.
    InvalidMetadata,
    /// The same key identifier was already provisioned in this store.
    DuplicateKeyId,
    /// The key was unknown, unavailable, or already consumed.
    KeyUnavailable,
    /// The requester and peer do not match the provisioned key record.
    Unauthorized,
}

impl core::fmt::Display for QkdProviderError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            f,
            "{}",
            match self {
                Self::InvalidMetadata => "invalid QKD key metadata",
                Self::DuplicateKeyId => "duplicate QKD key identifier",
                Self::KeyUnavailable => "QKD key unavailable",
                Self::Unauthorized => "QKD key requester or peer is unauthorized",
            }
        )
    }
}

impl std::error::Error for QkdProviderError {}

/// A single-use, 256-bit simulated QKD key, with secret bytes zeroized on drop.
///
/// `Debug` intentionally omits the secret. Never serialize or log the secret.
pub struct QkdKey {
    id: String,
    owner: String,
    peer: String,
    provenance: QkdProvenance,
    secret: Zeroizing<[u8; 32]>,
}

impl core::fmt::Debug for QkdKey {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("QkdKey")
            .field("id", &self.id)
            .field("owner", &self.owner)
            .field("peer", &self.peer)
            .field("provenance", &self.provenance)
            .field("secret", &"[REDACTED]")
            .finish()
    }
}

impl QkdKey {
    /// Public identifier to bind into the HPKE PSK context.
    pub fn id(&self) -> &str {
        &self.id
    }
    /// Identity of the party entitled to consume this copy.
    pub fn owner(&self) -> &str {
        &self.owner
    }
    /// Expected counterparty identity.
    pub fn peer(&self) -> &str {
        &self.peer
    }
    /// Identifies whether the key is simulation-only.
    pub fn provenance(&self) -> QkdProvenance {
        self.provenance
    }
    /// Borrow the secret for an immediate HPKE setup; do not persist the bytes.
    pub fn secret(&self) -> &[u8] {
        &self.secret[..]
    }
}

/// Per-party, in-memory store of single-use simulated QKD keys.
///
/// Independent Alice and Bob stores must be provisioned with matching
/// key identifiers and secret bytes by a trusted test coordinator.
#[derive(Default)]
pub struct QkdKeyStore {
    records: BTreeMap<String, QkdKey>,
    consumed_ids: BTreeSet<String>,
}

impl QkdKeyStore {
    /// Construct an empty per-party store.
    pub fn new() -> Self {
        Self::default()
    }

    /// Provision one simulation-only key for exactly one owner and peer.
    ///
    /// `secret` is moved into zeroizing storage; provisioning is for fixtures
    /// only and is not an authenticated network protocol.
    pub fn provision_fixture(
        &mut self,
        id: impl Into<String>,
        owner: impl Into<String>,
        peer: impl Into<String>,
        secret: [u8; 32],
    ) -> Result<(), QkdProviderError> {
        let id = id.into();
        let owner = owner.into();
        let peer = peer.into();
        let secret = Zeroizing::new(secret);
        if id.is_empty() || owner.is_empty() || peer.is_empty() || owner == peer {
            return Err(QkdProviderError::InvalidMetadata);
        }
        if self.records.contains_key(&id) || self.consumed_ids.contains(&id) {
            return Err(QkdProviderError::DuplicateKeyId);
        }
        self.records.insert(
            id.clone(),
            QkdKey {
                id,
                owner,
                peer,
                provenance: QkdProvenance::SimulationFixture,
                secret,
            },
        );
        Ok(())
    }

    /// Atomically remove and return a key only for the specified parties.
    ///
    /// A missing or previously consumed key fails closed. Wrong identities
    /// do not remove the key. Consumed material is never reinserted here.
    pub fn take_for(
        &mut self,
        id: &str,
        requester: &str,
        peer: &str,
    ) -> Result<QkdKey, QkdProviderError> {
        let existing = self
            .records
            .get(id)
            .ok_or(QkdProviderError::KeyUnavailable)?;
        if existing.owner != requester || existing.peer != peer {
            return Err(QkdProviderError::Unauthorized);
        }
        let key = self
            .records
            .remove(id)
            .ok_or(QkdProviderError::KeyUnavailable)?;
        self.consumed_ids.insert(id.to_owned());
        Ok(key)
    }
}
