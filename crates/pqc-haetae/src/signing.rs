//! Internal native HAETAE 1.2.0 signing orchestration.
//!
//! This module is experimental and is not a public signing API.

use crate::hyperball::{sample_hyperball, HyperballError};
use crate::packing::{unpack_secret_key, unpack_verification_key, PackingError};
use crate::params::signing_rejection_thresholds;
use crate::params::ParameterSet;
use crate::signature_packing::SignaturePackingError;
use crate::signing_challenge_prepare::prepare_signing_challenge_predecoded;
use crate::signing_init::derive_signing_initialization;
use crate::signing_init::SigningInitError;
use crate::signing_response::evaluate_signing_response_predecoded;
use crate::signing_signature_assembly::assemble_accepted_signature;

#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub(crate) enum SigningError {
    Initialization(SigningInitError),
    Hyperball(HyperballError),
    SignaturePacking(SignaturePackingError),
    KeyDecoding(PackingError),
}

impl From<SigningInitError> for SigningError {
    fn from(error: SigningInitError) -> Self {
        Self::Initialization(error)
    }
}

impl From<HyperballError> for SigningError {
    fn from(error: HyperballError) -> Self {
        Self::Hyperball(error)
    }
}

impl From<SignaturePackingError> for SigningError {
    fn from(error: SignaturePackingError) -> Self {
        Self::SignaturePacking(error)
    }
}

/// Validate serialized key components before entering the signing loop.
///
/// This establishes decoding validity, not mathematical keypair consistency.
fn validate_signing_key<const K: usize, const L: usize, const M: usize>(
    mode: ParameterSet,
    secret_key: &[u8],
) -> Result<
    (
        crate::packing::DecodedSecretKey<K, M>,
        crate::packing::ReconstructedVerificationKey<K, L>,
    ),
    SigningError,
> {
    let decoded = unpack_secret_key::<K, M>(secret_key, mode).map_err(SigningError::KeyDecoding)?;

    let verification_key = unpack_verification_key::<K, L>(&decoded.public_key, mode)
        .map_err(SigningError::KeyDecoding)?;

    Ok((decoded, verification_key))
}

/// Sign with the authenticated HAETAE retry sequence.
///
/// The hyperball sampler owns its internal rejection loop. This loop
/// handles the separate signing-response rejection condition.
fn sign_mode<const K: usize, const L: usize, const M: usize>(
    mode_number: u8,
    mode: ParameterSet,
    secret_key: &[u8],
    message: &[u8],
    context: &[u8],
    randomness: &[u8; 32],
) -> Result<Vec<u8>, SigningError> {
    let initialization =
        derive_signing_initialization(secret_key, message, context, randomness, mode)?;

    let (mut decoded, verification_key) = validate_signing_key::<K, L, M>(mode, secret_key)?;

    decoded.s0.ntt();
    decoded.s1.ntt();

    let thresholds = signing_rejection_thresholds(mode);

    let mut nonce = 0_u16;

    loop {
        let sample = sample_hyperball(mode_number, &initialization.signing_seed, nonce)?;
        nonce = sample.next_nonce;

        let prepared = prepare_signing_challenge_predecoded::<K, L>(
            mode_number,
            mode,
            &verification_key,
            &initialization.mu,
            &sample.y1,
            &sample.y2,
        );

        let response = evaluate_signing_response_predecoded::<K, L, M>(
            &decoded.s0,
            &decoded.s1,
            &prepared.challenge,
            sample.b,
            &sample.y1,
            &sample.y2,
            thresholds,
        );

        if (response.reject1 | response.reject2) != 0 {
            continue;
        }

        return Ok(assemble_accepted_signature::<K, L>(
            mode, &prepared, &response,
        )?);
    }
}

/// Internal deterministic signing entry point.
///
/// The caller supplies the 32-byte randomness input. No entropy is
/// generated by this function.
pub(crate) fn sign_deterministic(
    mode: ParameterSet,
    secret_key: &[u8],
    message: &[u8],
    context: &[u8],
    randomness: &[u8; 32],
) -> Result<Vec<u8>, SigningError> {
    match mode {
        ParameterSet::Haetae2 => {
            sign_mode::<2, 4, 3>(2, mode, secret_key, message, context, randomness)
        }
        ParameterSet::Haetae3 => {
            sign_mode::<3, 6, 5>(3, mode, secret_key, message, context, randomness)
        }
        ParameterSet::Haetae5 => {
            sign_mode::<4, 7, 6>(5, mode, secret_key, message, context, randomness)
        }
    }
}

// H1.3-E.7D.4C.10K.7 native signing verification regression
#[cfg(test)]
mod native_sign_verify_tests {
    use super::*;
    use crate::verification::verify_preformatted;
    use std::collections::BTreeMap;
    use std::path::Path;

    fn decode_hex(value: &str) -> Vec<u8> {
        assert_eq!(value.len() % 2, 0);
        value
            .as_bytes()
            .chunks_exact(2)
            .map(|pair| {
                u8::from_str_radix(std::str::from_utf8(pair).expect("hex UTF-8"), 16)
                    .expect("hex byte")
            })
            .collect()
    }

    fn cases(path: &Path) -> Vec<BTreeMap<String, String>> {
        let text = std::fs::read_to_string(path).expect("retry fixture");
        let mut result = Vec::new();
        let mut current: Option<BTreeMap<String, String>> = None;

        for line in text.lines() {
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };

            if key == "CASE" {
                assert!(current.is_none());
                let mut record = BTreeMap::new();
                record.insert(key.to_owned(), value.to_owned());
                current = Some(record);
            } else if key == "END_CASE" {
                let record = current.take().expect("case");
                assert_eq!(record["CASE"], value);
                result.push(record);
            } else if let Some(ref mut record) = current {
                if matches!(key, "PK" | "SK" | "RND" | "PRE" | "MESSAGE" | "SIGNATURE") {
                    assert!(record.insert(key.to_owned(), value.to_owned()).is_none());
                }
            }
        }

        assert!(current.is_none());
        assert_eq!(result.len(), 5);
        result
    }

    #[test]
    fn native_signatures_verify_and_reject_tampering() {
        let root = std::env::var("HAETAE_SIGNING_RETRY_PARITY_DIR")
            .expect("HAETAE_SIGNING_RETRY_PARITY_DIR required");

        let key_root = std::env::var("HAETAE_KEYGEN_KEYPAIR_PARITY_DIR")
            .expect("HAETAE_KEYGEN_KEYPAIR_PARITY_DIR required");

        let mut accepted = 0_usize;
        let mut rejected = 0_usize;

        for (number, mode) in [
            (2, ParameterSet::Haetae2),
            (3, ParameterSet::Haetae3),
            (5, ParameterSet::Haetae5),
        ] {
            let retry = cases(&Path::new(&root).join(format!("retry_mode{number}.txt")));

            let keys = cases(&Path::new(&key_root).join(format!("keypair_mode{number}.txt")));

            for (case, record) in retry.iter().enumerate() {
                let pk = decode_hex(&record["PK"]);
                let pre = decode_hex(&record["PRE"]);
                let message = decode_hex(&record["MESSAGE"]);
                let expected = decode_hex(&record["SIGNATURE"]);
                let rnd = decode_hex(&record["RND"]);

                assert!(!pre.is_empty());
                assert!(!message.is_empty());
                assert_eq!(rnd.len(), 32);
                assert_eq!(usize::from(pre[0]), pre.len() - 1);

                let sk = decode_hex(&keys[case]["SK"]);
                let randomness: [u8; 32] = rnd.try_into().expect("32-byte randomness");

                let signature = sign_deterministic(mode, &sk, &message, &pre[1..], &randomness)
                    .expect("native signing");

                assert_eq!(
                    signature, expected,
                    "mode={number} case={case} C-reference parity"
                );

                assert_eq!(
                    verify_preformatted(mode, &pk, &pre, &message, &signature,),
                    Ok(()),
                    "mode={number} case={case} native verification"
                );

                accepted += 1;

                let mut bad_message = message.clone();
                bad_message[0] ^= 1;

                assert!(verify_preformatted(mode, &pk, &pre, &bad_message, &signature).is_err());
                rejected += 1;

                let mut bad_pre = pre.clone();
                bad_pre[0] ^= 1;

                assert!(verify_preformatted(mode, &pk, &bad_pre, &message, &signature).is_err());
                rejected += 1;

                // Mutate actual context content, not only its length byte.
                assert!(
                    pre.len() > 1,
                    "authenticated fixture has no context: mode={number} case={case}"
                );
                let mut bad_context = pre.clone();
                bad_context[1] ^= 1;

                assert!(
                    verify_preformatted(mode, &pk, &bad_context, &message, &signature,).is_err(),
                    "modified context accepted: mode={number} case={case}"
                );
                rejected += 1;

                let mut bad_signature = signature.clone();
                bad_signature[0] ^= 1;

                assert!(verify_preformatted(mode, &pk, &pre, &message, &bad_signature).is_err());
                rejected += 1;

                println!(
                    "HAETAE_NATIVE_END_TO_END_MODE={number} \
                     CASE={case} STATUS=PASS"
                );
            }
        }

        assert_eq!(accepted, 15);
        assert_eq!(rejected, 60);

        println!("HAETAE_NATIVE_END_TO_END_ACCEPTED={accepted}");
        println!("HAETAE_NATIVE_END_TO_END_REJECTED={rejected}");
        println!("HAETAE_NATIVE_END_TO_END_STATUS=PASS");
    }

    #[test]
    fn malformed_signing_keys_return_typed_errors() {
        use crate::packing::{public_key_bytes, secret_key_bytes, PackingError};

        let randomness = [0_u8; 32];
        let mut checked = 0_usize;

        for mode in [
            ParameterSet::Haetae2,
            ParameterSet::Haetae3,
            ParameterSet::Haetae5,
        ] {
            let length = secret_key_bytes(mode);

            for invalid_length in [0, length - 1, length + 1] {
                let invalid = vec![0_u8; invalid_length];

                assert!(matches!(
                    sign_deterministic(mode, &invalid, b"message", b"", &randomness),
                    Err(SigningError::Initialization(
                        SigningInitError::InvalidSecretKeyLength
                    ))
                ));

                checked += 1;
            }

            let mut malformed = vec![0_u8; length];

            // The first secret polynomial follows the embedded public key.
            // Force a noncanonical small-polynomial coefficient.
            let offset = public_key_bytes(mode);

            malformed[offset] = match mode {
                ParameterSet::Haetae2 | ParameterSet::Haetae3 => 0x07,
                ParameterSet::Haetae5 => 0x03,
            };

            assert!(matches!(
                sign_deterministic(mode, &malformed, b"message", b"", &randomness),
                Err(SigningError::KeyDecoding(
                    PackingError::InvalidCoefficient { .. }
                ))
            ));

            checked += 1;
        }

        assert_eq!(checked, 12);

        println!("HAETAE_MALFORMED_SIGNING_KEY_CASES={} STATUS=PASS", checked);
    }

    #[test]
    fn embedded_public_key_canonicality_is_checked() {
        use crate::packing::{
            public_key_bytes, secret_key_bytes, unpack_verification_key, PackingError,
        };

        let randomness = [0_u8; 32];

        // HAETAE-5 uses 16-bit public coefficients, but Q = 64513.
        // The value 65535 is therefore noncanonical.
        let mut sk = vec![0_u8; secret_key_bytes(ParameterSet::Haetae5)];

        // Public key begins with a 32-byte seed.
        // The first polynomial coefficient follows immediately.
        sk[32] = 0xff;
        sk[33] = 0xff;

        assert!(matches!(
            sign_deterministic(ParameterSet::Haetae5, &sk, b"message", b"", &randomness,),
            Err(SigningError::KeyDecoding(
                PackingError::InvalidCoefficient {
                    index: 0,
                    value: 65535,
                }
            ))
        ));

        // HAETAE-2 and HAETAE-3 use the full 15-bit domain.
        // 0x7fff is canonical at the public-key decoding boundary.
        let mut canonical_checks = 0_usize;

        for (mode, k, l) in [
            (ParameterSet::Haetae2, 2_usize, 4_usize),
            (ParameterSet::Haetae3, 3_usize, 6_usize),
        ] {
            let mut pk = vec![0_u8; public_key_bytes(mode)];

            pk[32] = 0xff;
            pk[33] = 0x7f;

            let decoded = match (k, l) {
                (2, 4) => unpack_verification_key::<2, 4>(&pk, mode).is_ok(),
                (3, 6) => unpack_verification_key::<3, 6>(&pk, mode).is_ok(),
                _ => unreachable!("fixed test dimensions"),
            };

            assert!(decoded, "maximum 15-bit coefficient must decode");
            canonical_checks += 1;
        }

        assert_eq!(canonical_checks, 2);

        println!(
            "HAETAE_EMBEDDED_PUBLIC_KEY_NEGATIVE=1              CANONICAL_BOUNDARY=2 STATUS=PASS"
        );
    }

    #[test]
    fn signing_boundary_conditions_are_checked() {
        use crate::packing::secret_key_bytes;
        use crate::signing_init::{derive_signing_initialization, SigningInitError};

        for mode in [
            ParameterSet::Haetae2,
            ParameterSet::Haetae3,
            ParameterSet::Haetae5,
        ] {
            let length = secret_key_bytes(mode);
            let sk = vec![0_u8; length];
            let randomness = [0_u8; 32];

            for invalid_length in [0, length - 1, length + 1] {
                let invalid = vec![0_u8; invalid_length];
                assert!(matches!(
                    derive_signing_initialization(&invalid, b"message", b"", &randomness, mode,),
                    Err(SigningInitError::InvalidSecretKeyLength)
                ));
            }

            assert!(matches!(
                derive_signing_initialization(&sk, b"message", &[0_u8; 256], &randomness, mode,),
                Err(SigningInitError::ContextTooLong)
            ));

            for context in [vec![], vec![0_u8; 255]] {
                assert!(
                    derive_signing_initialization(&sk, b"", &context, &randomness, mode,).is_ok()
                );
            }
        }

        println!("HAETAE_SIGNING_BOUNDARY_MODES=3 STATUS=PASS");
    }
}
